CREATE DATABASE db_perpus_smkm3;
USE db_perpus_smkm3;

CREATE TABLE users(id INT AUTO_INCREMEMT PRIMARY KEY, username VARCHAR(50) NOT NULL, password VARCHAR(255) NOT NULL, nama_lengkap VARCHAR(100) NOT NULL);
CREATE TABLE buku(id INT AUTO_INCREMEMT PRIMARY KEY, judul VARCHAR(150) NOT NULL, pengarang VARCHAR(100) NOT NULL, penerbit VARCHAR(100) NOT NULL, tahun_terbit CHAR(4) NOT NULL, stok INT NOT NULL);